// Регистрируем поручения в общем журнале (QUESTS — js/data/quests.js).
BAG_QUESTS.forEach((b, i) => {
  const stages = b.kill ? ['work', 'ready', 'done'] : ['need_items', 'done'];
  const steps = b.kill
    ? [{ stage: 'work', text: () => bagKillText(b.id) }, { stage: 'ready', text: 'Сказать Заплечнику (нажать на сумку)' }]
    : b.needs.map((n, j) => ({ stage: 'need_items', text: () => questNeedText(b.id, j), done: () => questNeedMet(b.id, j) }))
        .concat([{ stage: 'need_items', text: 'Отдать Заплечнику (нажать на сумку)' }]);
  QUESTS[b.id] = Object.assign({
    stages, steps,
    desc: b.ask,
    giver: 'Заплечник', place: 'За плечом',
    journal: b.ask.replace(/\*[^*]+\*\s*/g, ''),
    offer: 'Заплечник чего-то хочет. Нажми на сумку в снаряжении.',
    offered: () => bagQuestIndex() === i && typeof bagMet === 'function' && bagMet() && state.player.level >= b.minLevel,
    reward: '+1 ячейка в сумке',
    bag: true,
  }, b);
});
