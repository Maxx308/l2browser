// ========================================================
//  WORKER: ТИКАЛКА
//  Работает в отдельном потоке браузера.
//  Каждые 100 мс посылает в основной поток команду «тик».
//  Браузер НЕ тормозит Worker в фоне — поэтому игра
//  идёт с полной скоростью даже в неактивной вкладке.
// ========================================================

const TICK_INTERVAL_MS = 100;

function tick() {
  postMessage('tick');
  setTimeout(tick, TICK_INTERVAL_MS);
}

tick();